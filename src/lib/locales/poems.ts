/**
 * 随机取一条诗句，并保证与上一次展示的不同。
 * 只有一条候选时不做去重（否则会死循环）。
 */
export function 取随机序号(排除序号: number): number {
  if (古诗词.length <= 1) return 0;
  let 序号 = Math.floor(Math.random() * 古诗词.length);
  if (序号 === 排除序号) 序号 = (序号 + 1) % 古诗词.length;
  return 序号;
}
